function unit(
  id: string,
  name: string,
  team: Team,
  level: number,
  attributes: Attributes,
  move: number,
  skillIds: string[],
  ai: AIRule[],
  sprite?: string,
): UnitDef {
  return {
    id,
    name,
    team,
    level,
    attributes,
    move,
    skills: skillIds,
    ai,
    ...(sprite ? { sprite } : {}),
  };
}

