function unit(
  id: string,
  name: string,
  team: Team,
  level: number,
  attributes: Attributes,
  move: number,
  skillIds: string[],
  ai: AIRule[],
  sprite: string,
  weaponType: DamageType,
  resist: Resistances = {},
): UnitDef {
  return {
    id,
    name,
    team,
    level,
    attributes,
    move,
    skills: skillIds,
    ai,
    sprite,
    weapon: weaponRange(level, weaponType),
    resist,
  };
}

/** Resistance points of armor suited to `level`: heavy armor (1) or light (0.4). */
const armor = (level: number, share: number, types: DamageType[]): Resistances =>
  Object.fromEntries(types.map((t) => [t, Math.round((6 * level + 10) * share)]));

