type Def = Omit<SkillDef, 'kind' | 'source' | 'side' | 'cooldown' | 'manaCost'> &
  Partial<Pick<SkillDef, 'kind' | 'source' | 'side' | 'cooldown' | 'manaCost'>>;

/** Fills in the common case: an enemy-targeted weapon damage skill with no cost. */
const skill = (d: Def): SkillDef => ({
  kind: 'damage',
  source: 'weapon',
  side: 'enemy',
  cooldown: 0,
  manaCost: 0,
  ...d,
});

